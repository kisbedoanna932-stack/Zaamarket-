-- À exécuter dans Supabase > SQL Editor sur un projet neuf.
-- Si vos tables existent déjà, NE RELANCEZ PAS ce script sans sauvegarde.
-- La clé sb_secret/service_role ne doit jamais être placée dans le site.

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  phone text,
  created_at timestamptz not null default now()
);

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  emoji text
);

create table if not exists public.app_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.stores (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  description text,
  country text not null default 'Burkina Faso',
  status text not null default 'pending' check(status in ('pending','approved','rejected')),
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  store_id uuid not null references public.stores(id) on delete cascade,
  category_id bigint references public.categories(id),
  name text not null,
  description text,
  price numeric(12,2) not null check(price >= 0),
  image_url text,
  stock integer not null default 0 check(stock >= 0),
  status text not null default 'pending' check(status in ('pending','active','rejected')),
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references auth.users(id),
  store_id uuid not null references public.stores(id),
  total numeric(12,2) not null default 0,
  country text not null default 'Burkina Faso',
  city text,
  delivery_address text,
  phone text,
  payment_method text not null default 'cash_on_delivery',
  payment_status text not null default 'pending',
  status text not null default 'pending',
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid not null references public.products(id),
  quantity integer not null check(quantity > 0),
  unit_price numeric(12,2) not null check(unit_price >= 0)
);

create or replace function public.is_admin()
returns boolean language sql stable security definer
set search_path = public
as $$ select exists(select 1 from public.app_admins where user_id = auth.uid()); $$;

alter table public.profiles enable row level security;
alter table public.categories enable row level security;
alter table public.app_admins enable row level security;
alter table public.stores enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

drop policy if exists "categories_public_read" on public.categories;
create policy "categories_public_read" on public.categories for select using (true);

drop policy if exists "profiles_read_own" on public.profiles;
create policy "profiles_read_own" on public.profiles for select to authenticated using (id = auth.uid());
drop policy if exists "profiles_update_own" on public.profiles;
create policy "profiles_update_own" on public.profiles for update to authenticated using (id = auth.uid()) with check (id = auth.uid());

drop policy if exists "admins_read_self" on public.app_admins;
create policy "admins_read_self" on public.app_admins for select to authenticated using (user_id = auth.uid());

drop policy if exists "stores_read_approved_or_owner" on public.stores;
create policy "stores_read_approved_or_owner" on public.stores for select using (status = 'approved' or owner_id = auth.uid() or public.is_admin());
drop policy if exists "stores_insert_pending" on public.stores;
create policy "stores_insert_pending" on public.stores for insert to authenticated with check (owner_id = auth.uid() and status = 'pending');
drop policy if exists "stores_admin_update" on public.stores;
create policy "stores_admin_update" on public.stores for update to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "products_read_active_or_owner_or_admin" on public.products;
create policy "products_read_active_or_owner_or_admin" on public.products for select using (
  (status = 'active' and exists(select 1 from public.stores s where s.id = store_id and s.status = 'approved'))
  or exists(select 1 from public.stores s where s.id = store_id and s.owner_id = auth.uid())
  or public.is_admin()
);
drop policy if exists "products_insert_pending_by_approved_store" on public.products;
create policy "products_insert_pending_by_approved_store" on public.products for insert to authenticated with check (
  status = 'pending' and exists(select 1 from public.stores s where s.id = store_id and s.owner_id = auth.uid() and s.status = 'approved')
);
drop policy if exists "products_admin_update" on public.products;
create policy "products_admin_update" on public.products for update to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "orders_customer_or_admin_read" on public.orders;
create policy "orders_customer_or_admin_read" on public.orders for select to authenticated using (customer_id = auth.uid() or public.is_admin() or exists(select 1 from public.stores s where s.id = store_id and s.owner_id = auth.uid()));
drop policy if exists "orders_customer_insert" on public.orders;
create policy "orders_customer_insert" on public.orders for insert to authenticated with check (customer_id = auth.uid());
drop policy if exists "orders_admin_update" on public.orders;
create policy "orders_admin_update" on public.orders for update to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "order_items_customer_or_admin_read" on public.order_items;
create policy "order_items_customer_or_admin_read" on public.order_items for select to authenticated using (
  public.is_admin() or exists(select 1 from public.orders o where o.id = order_id and o.customer_id = auth.uid())
);
